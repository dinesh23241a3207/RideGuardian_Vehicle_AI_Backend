# FINAL SUMMARY
# ==========================================================

print()
print("=" * 70)
print("SEQUENCE DATASET COMPLETE")
print("=" * 70)

print()

print(
    "Train sequences:",
    len(
        all_sequences["train"]
    )
)

print(
    "Validation sequences:",
    len(
        all_sequences["val"]
    )
)

print(
    "Test sequences:",
    len(
        all_sequences["test"]
    )
)

print()

print(
    "Sequence length:",
    SEQUENCE_LENGTH
)

print(
    "Stride:",
    STRIDE
)

print(
    "Sensor features:",
    len(FEATURE_COLUMNS)
)

print()

print(
    "Target:",
    TARGET_COLUMN
)

print()

print(
    "Output:"
)

print(
    OUTPUT_DIR
)

print()

print(
    "Manifest:"
)

print(
    manifest_path
)

print()

print("=" * 70)
print("RAW CSV WAS NOT MODIFIED")
print("=" * 70)